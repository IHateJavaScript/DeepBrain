def gradcam(model, img):
  with GradientTape() as tape:
    last_convlayer = model.get_layer('BlockGroup5__block_2__se_se_ex')
    model_in = Model([model.inputs], [model.outputs, last_convlayer.output])
    model_out, last_convlayer = model.input(img.reshape(1,244,244,3))
    class_out = model_out[:, np.argmax(model_out[0])] # colon means collect all
    grads = tape.gradient(class_out, last_convlayer)
    avg_grad = K.mean(grads, axis = (0, 1, 2))
  heatmap = tf.reduce_mean(tf.multiply(avg_grad, last_convlayer), axis = -1) #determine activation (hot area)
  heatmap = np.maximum(heatmap, 0) #intensifies hotter areas
  #np.seterr(divide = '')
  heatmap /= np.max(heatmap) # keeps numbers in a certain range of [0,1]
  heatmap = heatmap.reshape(8,8) #condense heatmap into kernel for overlay

  heatmap = cv2.resize(heatmap, (img.shape[0], img.shape[1]))
  colormap = cv2.applyColorMap(np.uint8(heatmap * 255), cv2.COLORMAP_JET)

  superimposed_img = ((colormap + img) * 180).astype(np.uint8) #overlay heat onto original, 180 is intesnity coefficient

  plt.imshow(superimposed_img)
  plt.show()

